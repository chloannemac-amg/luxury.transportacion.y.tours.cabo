const I18N = (() => {
  const ES = {};
  const nodes = document.querySelectorAll('[data-i18n]');
  const phNodes = document.querySelectorAll('[data-i18n-ph]');
  const metaDesc = document.querySelector('meta[name="description"]');

  // Capture the Spanish already in the page
  nodes.forEach(el => { ES[el.dataset.i18n] = el.innerHTML; });
  phNodes.forEach(el => { ES[el.dataset.i18nPh] = el.placeholder; });
  ES['meta.title'] = document.title;
  ES['meta.desc'] = metaDesc ? metaDesc.content : '';

  let current = 'es';

  function apply(lang) {
    const dict = lang === 'en' ? EN : ES;
    nodes.forEach(el => { const v = dict[el.dataset.i18n]; if (v !== undefined) el.innerHTML = v; });
    phNodes.forEach(el => { const v = dict[el.dataset.i18nPh]; if (v !== undefined) el.placeholder = v; });
    document.title = dict['meta.title'];
    if (metaDesc) metaDesc.content = dict['meta.desc'];
    document.documentElement.lang = lang;
    document.querySelectorAll('.lang-toggle button').forEach(b => {
      b.setAttribute('aria-pressed', String(b.dataset.lang === lang));
    });
    current = lang;
    try { localStorage.setItem('site-lang', lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  }

  // Spanish is the default; a visitor's saved choice wins
  let start = null;
  try { start = localStorage.getItem('site-lang'); } catch (e) {}
  apply(start === 'en' ? 'en' : 'es');

  document.querySelectorAll('.lang-toggle button').forEach(b => {
    b.addEventListener('click', () => apply(b.dataset.lang));
  });

  return { get lang() { return current; }, apply };
})();
